const std = @import("std");

const zstd_common = [_][]const u8{ "common/entropy_common.c", "common/error_private.c", "common/fse_decompress.c", "common/xxhash.c", "common/zstd_common.c" };
const zstd_decompress = [_][]const u8{ "decompress/huf_decompress.c", "decompress/zstd_ddict.c", "decompress/zstd_decompress.c", "decompress/zstd_decompress_block.c" };
const zstd_compress = [_][]const u8{ "compress/fse_compress.c", "compress/hist.c", "compress/huf_compress.c", "compress/zstd_compress.c", "compress/zstd_compress_literals.c", "compress/zstd_compress_sequences.c", "compress/zstd_compress_superblock.c", "compress/zstd_double_fast.c", "compress/zstd_fast.c", "compress/zstd_lazy.c", "compress/zstd_ldm.c", "compress/zstd_opt.c", "compress/zstd_preSplit.c" };

/// Add libzstd (lib/ of the zstdz flake input), encoder and decoder, to a
/// module: the packer's half.
fn addZstd(b: *std.Build, mod: *std.Build.Module, src: []const u8) void {
	const lib: std.Build.LazyPath = .{ .cwd_relative = b.pathJoin(&.{ src, "lib" }) };
	mod.addIncludePath(lib);
	const flags = [_][]const u8{ "-DZSTD_LEGACY_SUPPORT=0", "-DZSTD_DISABLE_ASM", "-DZSTD_TRACE=0" };
	mod.addCSourceFiles(.{ .root = lib, .files = &(zstd_common ++ zstd_decompress ++ zstd_compress), .flags = &flags });
}

/// Add the runtimes' small decoder: src/zdec_small.c, which compiles zstd's
/// educational decoder (doc/educational_decoder of the zstdz input) as one unit.
fn addZstdSmall(b: *std.Build, mod: *std.Build.Module, src: []const u8) void {
	mod.addIncludePath(.{ .cwd_relative = b.pathJoin(&.{ src, "doc", "educational_decoder" }) });
	mod.addCSourceFile(.{ .file = b.path("src/zdec_small.c"), .flags = &.{ "-std=c11", "-ffunction-sections", "-fdata-sections" } });
}

/// musl's Linux headers from Zig's own lib directory, for C compiled without
/// linking a C library (declarations and constants only).
fn addMuslHeaders(b: *std.Build, mod: *std.Build.Module, arch: std.Target.Cpu.Arch) void {
	const inc = b.graph.zig_lib_directory.join(b.allocator, &.{ "libc", "include" }) catch @panic("OOM");
	const family = switch (arch) {
		.x86_64 => "x86",
		.aarch64 => "aarch64",
		else => @panic("libc-free runtimes support x86_64 and aarch64"),
	};
	for ([_][]const u8{ b.fmt("{s}-linux-musl", .{@tagName(arch)}), "generic-musl", b.fmt("{s}-linux-any", .{family}), "any-linux-any" }) |dir|
		mod.addSystemIncludePath(.{ .cwd_relative = b.pathJoin(&.{ inc, dir }) });
}

/// Runtime targets: index name (as in src/targets.zig) and Zig target triple.
const runtime_targets = [_][2][]const u8{
	.{ "linux-x86_64", "x86_64-linux-musl" },
	.{ "linux-aarch64", "aarch64-linux-musl" },
	.{ "macos-x86_64", "x86_64-macos" },
	.{ "macos-arm64", "aarch64-macos" },
	.{ "freebsd-x86_64", "x86_64-freebsd" },
	.{ "freebsd-aarch64", "aarch64-freebsd" },
	.{ "netbsd-x86_64", "x86_64-netbsd" },
};

/// Cross-build rocosmo-runtime for every target (ReleaseSmall, stripped,
/// small zstd decoder), install each under zig-out/runtime/, gzip it with
/// `gzip -9 -n` (no name or timestamp, so output is reproducible) and expose
/// the gzipped bytes as the generated "runtimes" module for the packer.
fn runtimesModule(b: *std.Build, zstd_src: []const u8, version: []const u8) *std.Build.Module {
	const wf = b.addWriteFiles();
	var table: std.ArrayList(u8) = .empty;
	table.appendSlice(b.allocator, "//! Generated by build.zig: gzipped rocosmo-runtime per OS/CPU.\npub const Runtime = struct { name: []const u8, gz: []const u8 };\npub const all = [_]Runtime{\n") catch @panic("OOM");
	for (runtime_targets) |rt| {
		const query = std.Target.Query.parse(.{ .arch_os_abi = rt[1] }) catch @panic("bad runtime triple");
		const t = b.resolveTargetQuery(query);
		// Linux runtimes link no C library: nolibc_linux.c supplies the few
		// functions used, compiled against musl's headers (prototypes only).
		const libc = t.result.os.tag != .linux;
		const core = b.createModule(.{ .root_source_file = b.path("src/rt_ffi.zig"), .target = t, .optimize = .ReleaseSmall, .link_libc = libc, .strip = true, .single_threaded = true, .unwind_tables = .none });
		if (!libc) addMuslHeaders(b, core, t.result.cpu.arch);
		addZstdSmall(b, core, zstd_src);
		const core_lib = b.addLibrary(.{ .name = "rocosmo_rt", .root_module = core, .linkage = .static });
		const mod = b.createModule(.{ .target = t, .optimize = .ReleaseSmall, .link_libc = libc, .strip = true, .single_threaded = true, .unwind_tables = .none });
		if (!libc) {
			addMuslHeaders(b, mod, t.result.cpu.arch);
			mod.addCSourceFile(.{ .file = b.path("src/nolibc_linux.c"), .flags = &.{ "-std=c11", "-Wall", "-Wextra", "-Werror", "-fno-builtin", "-fno-stack-protector", "-ffunction-sections", "-fdata-sections" } });
		}
		mod.addCSourceFile(.{ .file = b.path("src/runtime.c"), .flags = &.{ "-std=c11", "-Wall", "-Wextra", "-Werror", "-D_POSIX_C_SOURCE=200809L", "-D_DARWIN_C_SOURCE", "-D_BSD_SOURCE", "-ffunction-sections", "-fdata-sections" } });
		mod.addIncludePath(b.path("src"));
		mod.addCMacro("ROCOSMO_VERSION", b.fmt("\"{s}\"", .{version}));
		mod.addCMacro("ROCOSMO_PLATFORM", b.fmt("\"{s}\"", .{rt[0]}));
		mod.linkLibrary(core_lib);
		const exe = b.addExecutable(.{ .name = "rocosmo-runtime", .root_module = mod });
		b.getInstallStep().dependOn(&b.addInstallFileWithDir(exe.getEmittedBin(), .{ .custom = "runtime" }, rt[0]).step);
		const gz = b.addSystemCommand(&.{ "gzip", "-9", "-n", "-c" });
		gz.addFileArg(exe.getEmittedBin());
		const gz_name = b.fmt("{s}.gz", .{rt[0]});
		_ = wf.addCopyFile(gz.captureStdOut(.{}), gz_name);
		table.print(b.allocator, "\t.{{ .name = \"{s}\", .gz = @embedFile(\"{s}\") }},\n", .{ rt[0], gz_name }) catch @panic("OOM");
	}
	table.appendSlice(b.allocator, "};\n") catch @panic("OOM");
	const src = wf.add("runtimes.zig", table.items);
	return b.createModule(.{ .root_source_file = src });
}

pub fn build(b: *std.Build) void {
	const target = b.standardTargetOptions(.{});
	const optimize = b.option(std.builtin.OptimizeMode, "optimize", "Optimization mode (default: ReleaseFast)") orelse .ReleaseFast;
	const version = "0.1.0";
	// zstd sources come from the flake (zstdz input); nix develop exports ROCOSMO_ZSTD_SRC.
	const zstd_src = b.option([]const u8, "zstd-src", "zstd source tree (default: $ROCOSMO_ZSTD_SRC from nix develop)") orelse
		b.graph.environ_map.get("ROCOSMO_ZSTD_SRC") orelse @panic("set -Dzstd-src or run inside nix develop");

	const lib_mod = b.createModule(.{ .root_source_file = b.path("src/ffi.zig"), .target = target, .optimize = optimize, .link_libc = true });
	addZstd(b, lib_mod, zstd_src);
	lib_mod.addImport("runtimes", runtimesModule(b, zstd_src, version));
	const lib = b.addLibrary(.{ .name = "rocosmo", .root_module = lib_mod, .linkage = .static });

	const strip = b.option(bool, "strip", "Strip debug info from rocosmo-pack (default: false)") orelse false;
	const exe_mod = b.createModule(.{ .target = target, .optimize = optimize, .link_libc = true, .strip = strip });
	exe_mod.addCSourceFile(.{ .file = b.path("src/rocosmo_pack.c"), .flags = &.{ "-std=c11", "-Wall", "-Wextra", "-Werror" } });
	exe_mod.addIncludePath(b.path("src"));
	exe_mod.addCMacro("ROCOSMO_VERSION", "\"" ++ version ++ "\"");
	const t = target.result;
	exe_mod.addCMacro("ROCOSMO_PLATFORM", b.fmt("\"{s}-{s}\"", .{ @tagName(t.os.tag), @tagName(t.cpu.arch) }));
	exe_mod.linkLibrary(lib);
	const exe = b.addExecutable(.{ .name = "rocosmo-pack", .root_module = exe_mod });
	b.installArtifact(exe);

	const test_mod = b.createModule(.{ .root_source_file = b.path("src/tests.zig"), .target = target, .optimize = optimize, .link_libc = true });
	addZstd(b, test_mod, zstd_src);
	addZstdSmall(b, test_mod, zstd_src);
	const tests = b.addTest(.{ .root_module = test_mod });
	const test_step = b.step("test", "Run core unit tests");
	test_step.dependOn(&b.addRunArtifact(tests).step);
}
